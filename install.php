<?php
/**
 * One-time installer: writes config.php, creates the tables, creates the
 * admin account and (optionally) loads sample trips & Hurghada places.
 */
define('INSTALLER', true);
require __DIR__ . '/includes/bootstrap.php';
require __DIR__ . '/includes/schema.php';

start_session();
$installed = is_installed();
$errors = [];
$v = [
    'driver' => $_POST['driver'] ?? 'mysql',
    'host'   => trim($_POST['host'] ?? 'localhost'),
    'name'   => trim($_POST['name'] ?? ''),
    'user'   => trim($_POST['user'] ?? ''),
    'admin_user' => trim($_POST['admin_user'] ?? 'admin'),
    'admin_name' => trim($_POST['admin_name'] ?? ''),
    'seed'   => isset($_POST['seed']) || $_SERVER['REQUEST_METHOD'] !== 'POST',
];

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    verify_csrf();
    $pass = (string)($_POST['pass'] ?? '');
    $adminPass = (string)($_POST['admin_pass'] ?? '');

    if (!in_array($v['driver'], ['mysql', 'sqlite'], true)) {
        $errors[] = 'نوع قاعدة بيانات غير صالح.';
    }
    if ($v['driver'] === 'mysql' && ($v['name'] === '' || $v['user'] === '')) {
        $errors[] = 'اكتب اسم قاعدة البيانات واسم المستخدم كما أنشأتهما في لوحة هوستنجر.';
    }
    if (!preg_match('/^[A-Za-z0-9_.-]{3,60}$/', $v['admin_user'])) {
        $errors[] = 'اسم مستخدم الأدمن يجب أن يكون 3 أحرف على الأقل (حروف إنجليزية وأرقام).';
    }
    if (mb_strlen($adminPass) < 8) {
        $errors[] = 'كلمة مرور الأدمن يجب ألا تقل عن 8 أحرف.';
    }
    if (!is_writable(__DIR__)) {
        $errors[] = 'المجلد الرئيسي غير قابل للكتابة، لا يمكن إنشاء ملف config.php.';
    }

    if (!$errors) {
        $db = $v['driver'] === 'sqlite'
            ? ['driver' => 'sqlite', 'path' => 'data/eagles.sqlite']
            : ['driver' => 'mysql', 'host' => $v['host'] ?: 'localhost', 'port' => 3306, 'name' => $v['name'], 'user' => $v['user'], 'pass' => $pass];
        $runtimeDb = $db;
        if ($db['driver'] === 'sqlite') {
            $runtimeDb['path'] = __DIR__ . '/data/eagles.sqlite';
        }
        try {
            $pdo = make_pdo($runtimeDb);
            install_schema($pdo, $db['driver']);

            $count = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
            if ($count === 0) {
                $pdo->prepare('INSERT INTO users (username, full_name, password_hash, created_at) VALUES (?,?,?,?)')
                    ->execute([$v['admin_user'], $v['admin_name'] ?: $v['admin_user'], password_hash($adminPass, PASSWORD_DEFAULT), now()]);
            } else {
                $pdo->prepare('UPDATE users SET password_hash = ? WHERE username = ?')
                    ->execute([password_hash($adminPass, PASSWORD_DEFAULT), $v['admin_user']]);
            }
            if ($v['seed'] && (int)$pdo->query('SELECT COUNT(*) FROM trips')->fetchColumn() === 0) {
                seed_sample_content($pdo);
            }

            $cfgDb = var_export($db, true);
            if ($db['driver'] === 'sqlite') {
                $cfgDb = str_replace("'data/eagles.sqlite'", "__DIR__ . '/data/eagles.sqlite'", $cfgDb);
            }
            $config = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . "\nreturn [\n"
                . "    'db' => $cfgDb,\n"
                . "    // اتركه فارغاً ليتم اكتشاف رابط الموقع تلقائياً، أو اكتب مثلاً 'https://eagles-tourism.com'\n"
                . "    'site_url' => '',\n"
                . "    'debug' => false,\n];\n";
            if (file_put_contents(__DIR__ . '/config.php', $config) === false) {
                throw new RuntimeException('تعذر كتابة ملف config.php');
            }
            @chmod(__DIR__ . '/config.php', 0640);
            file_put_contents(__DIR__ . '/data/installed.lock', date('c'));
            $installed = true;
            $justInstalled = true;
        } catch (Throwable $ex) {
            $errors[] = 'تعذر الاتصال بقاعدة البيانات أو إنشاء الجداول: ' . $ex->getMessage();
        }
    }
}
